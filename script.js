function getPreviewUrl(item) {
    // Своя картинка приоритетнее, иначе автоскриншот сайта
    return item.image || `https://s0.wp.com/mshots/v1/${encodeURIComponent(item.url)}?w=800&h=500`;
}

function getHost(url) {
    try {
        return new URL(url).hostname.replace(/^www\./, '');
    } catch (e) {
        return url;
    }
}

function renderPortfolio(lang) {
    const grid = document.getElementById('portfolioGrid');
    if (!grid) return;

    const openText = (translations[lang] && translations[lang].portfolio_open) || translations.en.portfolio_open;

    grid.innerHTML = portfolioItems.map(item => {
        const title = (item.title && (item.title[lang] || item.title.en)) || '';
        const desc = (item.desc && (item.desc[lang] || item.desc.en)) || '';
        const tags = (item.tags || []).map(t => `<span class="tag">${t}</span>`).join('');

        return `
        <a class="portfolio-card" href="${item.url}" target="_blank" rel="noopener noreferrer">
            <div class="portfolio-preview">
                <i class="fa-solid fa-globe"></i>
                <img src="${getPreviewUrl(item)}" alt="${title}" loading="lazy">
            </div>
            <div class="portfolio-body">
                <h3>${title}</h3>
                <p class="portfolio-desc">${desc}</p>
                <div class="portfolio-tags">${tags}</div>
                <span class="portfolio-link"><i class="fa-solid fa-arrow-up-right-from-square"></i> ${getHost(item.url)} · ${openText}</span>
            </div>
        </a>`;
    }).join('');

    // Если превью не загрузилось, остаётся иконка-заглушка
    grid.querySelectorAll('.portfolio-preview img').forEach(img => {
        img.addEventListener('error', () => { img.style.display = 'none'; });
    });
}

// Функция перевода
function setLanguage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.innerHTML = translations[lang][key];
        }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    renderPortfolio(lang);

    localStorage.setItem('preferred_lang', lang);
}

document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
        setLanguage(btn.getAttribute('data-lang'));
    });
});

document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('preferred_lang') || 'en';
    setLanguage(savedLang);
});

// Управление мобильным гамбургер-меню
const hamburgerBtn = document.getElementById('hamburgerBtn');
const navContainer = document.getElementById('navContainer');

if (hamburgerBtn && navContainer) {
    hamburgerBtn.addEventListener('click', () => {
        navContainer.classList.toggle('active');
        const icon = hamburgerBtn.querySelector('i');
        if (icon) {
            icon.classList.toggle('fa-bars');
            icon.classList.toggle('fa-xmark');
        }
    });

    // Автоматическое закрытие меню при клике на любую ссылку
    document.querySelectorAll('.nav-links a').forEach(link => {
        link.addEventListener('click', () => {
            navContainer.classList.remove('active');
            const icon = hamburgerBtn.querySelector('i');
            if (icon) {
                icon.classList.add('fa-bars');
                icon.classList.remove('fa-xmark');
            }
        });
    });
}

// Плавное появление секций
const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.style.opacity = '1';
            entry.target.style.transform = 'translateY(0)';
        }
    });
}, { threshold: 0.1 });

document.querySelectorAll('.section').forEach(section => {
    section.style.opacity = '0';
    section.style.transform = 'translateY(25px)';
    section.style.transition = 'all 0.5s ease-out';
    observer.observe(section);
});